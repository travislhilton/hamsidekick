def is_land(lat: float, lon: float) -> bool:
    """True when this point is on land (to the map's 2-degree cells: a coast or a small island may go either way)."""
    r = min(ROWS - 1, max(0, int((90.0 - float(lat)) // STEP)))
    c = int(((float(lon) + 180.0) % 360.0) // STEP) % COLS
    i = r * COLS + c
    return bool(_BITS[i >> 3] >> (7 - (i & 7)) & 1)
